const AnimatedSignature = () => {
  const svgRef = useRef(null);
  const containerRef = useRef(null);

  const playAnimation = () => {
    if (!svgRef.current) return;
    const paths = svgRef.current.querySelectorAll('.signature-glyph');

    // 1. Reset each path with total length
    paths.forEach((path) => {
      const length = path.getTotalLength();
      path.style.strokeDasharray = `${length}`;
      path.style.strokeDashoffset = `${length}`;
      path.style.fillOpacity = '0';
    });

    const tl = gsap.timeline();

    // 2. Animate stroke sequentially (pen tracing outline)
    tl.to(paths, {
      strokeDashoffset: 0,
      duration: 1.4,
      stagger: 0.1,
      ease: 'power2.inOut',
    })
    // 3. Smoothly flood in glowing calligraphy ink
    .to(
      paths,
      {
        fillOpacity: 0.95,
        duration: 0.6,
        stagger: 0.05,
        ease: 'power1.out',
      },
      '-=0.4'
    );
  };

  useEffect(() => {
    if (!svgRef.current || !containerRef.current) return;

    const paths = svgRef.current.querySelectorAll('.signature-glyph');
    paths.forEach((path) => {
      const length = path.getTotalLength();
      path.style.strokeDasharray = `${length}`;
      path.style.strokeDashoffset = `${length}`;
      path.style.fillOpacity = '0';
    });

    const trigger = ScrollTrigger.create({
      trigger: containerRef.current,
      start: 'top 90%',
      onEnter: () => playAnimation(),
      once: false,
    });

    return () => trigger.kill();
  }, []);

  return (
    <div
      ref={containerRef}
      className="w-48 sm:w-56 md:w-64 h-auto flex flex-col items-center md:items-end justify-center relative group cursor-pointer select-none"
      onClick={playAnimation}
      title="Click to replay signature"
    >
      {/* Ambient background glow */}
      <div className="absolute top-1/2 left-1/2 -translate-x-1/2 -translate-y-1/2 w-48 h-16 bg-purple-500/15 rounded-full blur-2xl pointer-events-none group-hover:bg-fuchsia-500/25 transition-all duration-500" />

      {/* SVG Calligraphy Signature of Alfiya */}
      <svg
        ref={svgRef}
        id="Visual"
        xmlns="http://www.w3.org/2000/svg"
        viewBox="40 40 310 160"
        className="w-full h-auto max-h-20 sm:max-h-24 object-contain filter drop-shadow-[0_0_16px_rgba(192,132,252,0.6)] group-hover:scale-105 transition-transform duration-300 z-10"
      >
        <defs>
          <linearGradient id="signature-grad-alfiya" x1="0%" y1="0%" x2="100%" y2="0%">
            <stop offset="0%" stopColor="#f43f5e" />
            <stop offset="35%" stopColor="#ec4899" />
            <stop offset="70%" stopColor="#c084fc" />
            <stop offset="100%" stopColor="#38bdf8" />
          </linearGradient>
          <filter id="sig-glow-alfiya" x="-20%" y="-20%" width="140%" height="140%">
            <feGaussianBlur stdDeviation="2.2" result="blur" />
            <feMerge>
              <feMergeNode in="blur" />
              <feMergeNode in="SourceGraphic" />
            </feMerge>
          </filter>
        </defs>

        <g
          stroke="url(#signature-grad-alfiya)"
          strokeWidth="1.8"
          strokeLinecap="round"
          strokeLinejoin="round"
          filter="url(#sig-glow-alfiya)"
        >
          {glyphPaths.map((glyph) => (
            <path
              key={glyph.id}
              id={`glyph-${glyph.id}`}
              className="signature-glyph"
              d={glyph.d}
              fill="url(#signature-grad-alfiya)"
              style={{ fillOpacity: 0 }}
            />
          ))}
        </g>
      </svg>
    </div>
  );
};

export default AnimatedSignature;
